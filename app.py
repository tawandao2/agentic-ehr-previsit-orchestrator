"""Clinician approval screen. Run:  python -m streamlit run app.py"""
import os, sys, pathlib
import duckdb, streamlit as st
sys.path.insert(0, str(pathlib.Path(__file__).parent / "src"))
from agent import run_agent
from demo_llm import RulesOnlyLLM
import fhir_sink

DB = os.environ.get("EHR_DB", "data/ehr_demo.duckdb")
OUTBOX = os.environ.get("EHR_OUTBOX", "outbox")

st.set_page_config(page_title="Pre-Visit Chart Orchestrator", layout="wide")
st.title("Pre-Visit Chart Orchestrator")
st.warning("Synthetic patients only (Synthea). Demonstration project, not for clinical use. "
           "Nothing is written until a clinician attests.")


@st.cache_resource
def con():
    return duckdb.connect(DB, read_only=True)


def describe(rid):
    if rid.startswith("gap:"):
        return f"Rule result {rid.split(':')[1]}"
    for tbl, col in (("conditions", "display"), ("observations", "display"), ("medications", "display"), ("procedures", "display")):
        r = con().execute(f"select '{tbl[:-1]}', {col} from {tbl} where id=?", [rid]).fetchone()
        if r:
            return f"{r[0]}: {r[1]}"
    return "unknown resource"


cohort = con().execute("select patient_id, age, n_gaps from cohort order by n_gaps desc, patient_id").fetchall()
left, right = st.columns([1, 2])
with left:
    pid = st.selectbox("Upcoming appointment", [c[0] for c in cohort],
                       format_func=lambda p: next(f"{p[:8]}  |  age {c[1]}  |  {c[2]} gap(s)" for c in cohort if c[0] == p))
    mode = st.radio("Brief writer", ["Demo (rules only, no AI)", "Gemini agent"],
                    help="The Gemini agent needs GEMINI_API_KEY set. Both modes go through the same citation checks.")
    if st.button("Prepare brief", type="primary"):
        try:
            llm = RulesOnlyLLM()
            if mode == "Gemini agent":
                from agent import GeminiLLM
                llm = GeminiLLM()
            st.session_state["result"] = run_agent(pid, DB, llm)
        except Exception as e:
            st.session_state["result"] = {"status": "error", "problems": [str(e)]}

res = st.session_state.get("result")
with right:
    if not res:
        st.info("Pick an appointment and prepare a brief.")
    elif res["status"] != "ready_for_review":
        st.error(f"No brief shown ({res['status']}). " + "; ".join(res.get("problems", [res.get("reason", "")])))
    else:
        st.subheader("Pre-visit brief")
        for s in res["brief"]["statements"]:
            st.markdown(f"**{s['kind'].replace('_', ' ').title()}**: {s['text']}")
            with st.expander(f"Sources ({len(s['source_ids'])})"):
                for rid in s["source_ids"]:
                    st.code(f"{rid}\n{describe(rid)}", language=None)
        st.subheader("Draft orders (generated by rules, not by the AI)")
        chosen = [o for n, o in enumerate(res["draft_orders"])
                  if st.checkbox(o["description"], value=True, key=f"o{n}{res['patient_id']}")]
        if not res["draft_orders"]:
            st.write("No orders suggested.")
        clinician = st.text_input("Clinician name")
        attest = st.checkbox("I have reviewed this brief and the selected orders and I take responsibility for them.")
        c1, c2 = st.columns(2)
        if c1.button("Approve and push to test EHR"):
            try:
                ids = fhir_sink.approve(res["patient_id"], chosen, clinician, attest, OUTBOX)
                st.success(f"Wrote {len(ids)} ServiceRequest resource(s) to the local test outbox.")
            except (PermissionError, ValueError) as e:
                st.error(str(e))
        if c2.button("Reject brief"):
            fhir_sink.reject(res["patient_id"], clinician, "rejected by clinician", OUTBOX)
            st.info("Rejection recorded in the audit log.")

with st.expander("Audit log"):
    st.dataframe(fhir_sink.read_audit(OUTBOX)[::-1] or [{"note": "empty"}])
